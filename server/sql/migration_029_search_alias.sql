-- ============================================
-- 搜索别名映射表: 用户模糊搜索词 → 平台内容体系
-- 运营可随时增删改, 无需修改 Java 代码
-- ============================================
CREATE TABLE IF NOT EXISTS t_search_alias (
    id          BIGINT AUTO_INCREMENT PRIMARY KEY,
    alias       VARCHAR(100) NOT NULL COMMENT '用户输入的搜索词',
    target_category VARCHAR(50)  DEFAULT NULL COMMENT '映射到的目标分类',
    target_keyword  VARCHAR(100) DEFAULT NULL COMMENT '映射到的目标关键词',
    weight      DOUBLE DEFAULT 0.8 COMMENT '权重 0-1',
    source      TINYINT DEFAULT 0 COMMENT '0=运营配置 1=自动挖掘',
    create_time DATETIME DEFAULT CURRENT_TIMESTAMP,
    INDEX idx_alias (alias)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='搜索别名映射';

